"""Generates lean/TrainNetwork/Brute/CrossCheck.lean.

For a fixed list of tiny instances it writes the instance as a Lean `Instance` and a
`#guard` that the Lean-verified exhaustive solver `Brute.bruteCost` returns the optimum
computed here by the independent Python solvers (`brute`, `exact` and CP-SAT, which must
agree). This ties the Lean reading of docs/problem.md to the Python one.

    python scripts/lean_crosscheck.py > lean/TrainNetwork/Brute/CrossCheck.lean
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from network_solver import brute, cpsat, exact, verify  # noqa: E402
from network_solver.families import from_ascii, plus_instance  # noqa: E402
from network_solver.generate import random_instance  # noqa: E402

MAX_CANDIDATES = 40_000


def cells(cs) -> str:
    cs = sorted(cs)
    return "∅" if not cs else "{" + ", ".join(f"({x}, {y})" for x, y in cs) + "}"


def cost(inst, sol):
    if sol is None:
        return None
    report = verify.check(inst, sol)
    assert report.ok, report.errors
    return report.cost


def instances():
    out = [("plus", plus_instance()),
           ("crossing", from_ascii(["#1#", "2.a", "#b#"], k=2)),
           ("tie", from_ascii(["a.1.b"], k=1)),
           ("detour", from_ascii(["1.a", "#.#", "2.b"], k=2)),
           # the centre cannot serve all four directions: both ports reach `a` the long way
           ("excess", from_ascii(["#2#", "1.a", "#..", "#b."], k=2))]
    for i, (w, h, p, c, k) in enumerate([(3, 2, 1, 2, 2), (2, 3, 2, 2, 1), (3, 3, 1, 3, 2),
                                         (3, 3, 2, 2, 2), (4, 2, 2, 2, 1), (3, 3, 2, 3, 2),
                                         (2, 4, 1, 3, 3), (3, 3, 1, 4, 3)]):
        for seed in range(3):
            fraction = [0.15, 0.3, 0.45][seed] if w * h > 6 else [0.0, 0.1, 0.2][seed]
            try:
                inst = random_instance(w, h, p, c, k, blocked_fraction=fraction, seed=700 + 10 * i + seed)
            except RuntimeError:
                continue
            candidates = 2 ** len(brute.all_edges(inst)) * 2 ** (len(inst.cities) * len(inst.ports))
            if candidates <= MAX_CANDIDATES:
                out.append((f"r{i}_{seed}", inst))
    return out


def main() -> None:
    print("/-")
    print("GENERATED by scripts/lean_crosscheck.py. Do not edit by hand.")
    print("")
    print("Tests, not proofs: each `#guard` runs the Lean-verified exhaustive solver on a tiny")
    print("instance and compares (excess, tiles) with the value computed by the Python solvers")
    print("(`brute`, `exact` and CP-SAT, which agree). `none` means infeasible.")
    print("-/")
    print("import TrainNetwork.Brute.Solve")
    print("")
    print("namespace TrainNetwork.Brute.CrossCheck")
    for name, inst in instances():
        want = cost(inst, brute.solve(inst)[0])
        assert want == cost(inst, exact.solve(inst)[0]) == cost(inst, cpsat.solve(inst, time_limit=60)[0])
        print("")
        print(f"def {name} : Instance where")
        print(f"  W := {inst.width}")
        print(f"  H := {inst.height}")
        print(f"  blocked := {cells(inst.blocked)}")
        print(f"  ports := {cells(inst.ports.values())}")
        print(f"  cities := {cells(inst.cities.values())}")
        print(f"  k := {inst.k}")
        for field in ("k_pos", "ports_cities", "ports_unblocked", "cities_unblocked",
                      "ports_inBounds", "cities_inBounds"):
            print(f"  {field} := by decide")
        rhs = "none" if want is None else f"some (({want[0]} : ℕ∞), {want[1]})"
        print(f"#guard bruteCost {name} == {rhs}")
    print("")
    print("end TrainNetwork.Brute.CrossCheck")


if __name__ == "__main__":
    main()
